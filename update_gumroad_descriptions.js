async function updateProduct(p) {
  const body = new URLSearchParams();
  body.append('name', p.name);
  body.append('description', p.description);
  body.append('price', String(p.price));
  body.append('customizable_price', 'false');
  body.append('published', 'true');

  try {
    const res = await fetch('https://api.gumroad.com/v2/products/' + p.id, {
      method: 'PUT',
      headers: {
        'Authorization': 'Bearer ' + token,
        'Content-Type': 'application/x-www-form-urlencoded'
      },
      body
    });
    const data = await res.json();
    if (data.success) {
      console.log('  OK ' + p.name);
    } else {
      console.log('  FAIL ' + p.name + ': ' + (data.message || ''));
    }
  } catch (e) {
    console.log('  ERROR ' + p.name + ': ' + e.message);
  }
}

